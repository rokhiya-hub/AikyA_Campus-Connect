import React from "react";
import { render, screen, fireEvent, cleanup } from "@testing-library/react";
import { MemoryRouter } from "react-router-dom";
import NotificationCenter from "../src/components/NotificationCenter.jsx";
import NotificationAdmin from "../src/components/NotificationAdmin.jsx";
import Events from "../src/pages/Events.jsx";
import { api } from "../src/api/client.js";
import { campusTimestamp, campusISO, campusInput, upcomingEvents } from "../src/lib/notificationTime.js";
let mockUser = null;
let mockCampus;
jest.mock("../src/lib/useUniverse.js", () => ({ useUniverse: () => mockCampus }));
jest.mock("../src/context/AuthContext.jsx", () => ({ useAuth: () => ({ user: mockUser }) }));
jest.mock("../src/api/client.js", () => ({ api: { pushConfig: jest.fn().mockResolvedValue({ enabled: false }), notifications: jest.fn(), readNotification: jest.fn(), adminNotifications: jest.fn(), saveNotification: jest.fn(), cancelNotification: jest.fn(), notificationDeliveries: jest.fn() } }));
jest.mock("../src/lib/pushNotifications.js", () => ({ pushSupported: () => false }));
const note = { _id: "000000000000000000000001", title: "Synthetic verified notice", body: "Synthetic body", type: "announcement", scheduledAt: "2020-01-01T00:00:00Z", expiresAt: "2099-01-01T00:00:00Z", readAt: null };
const mount = element => render(<MemoryRouter future={{ v7_startTransition: true, v7_relativeSplatPath: true }}>{element}</MemoryRouter>);
beforeEach(() => { mockUser = null; localStorage.clear(); api.notifications.mockResolvedValue({ items: [note], hasMore: false }); api.readNotification.mockResolvedValue({}); api.adminNotifications.mockResolvedValue({ items: [], hasMore: false }); });
afterEach(() => { cleanup(); jest.clearAllMocks(); });
test("calendar retains demo records but upcoming and deadline views require verified timestamps", () => {
  const verified = { _id: "verified", title: "Synthetic verified event", date: "2099-01-02", startsAt: "2099-01-02T06:00:00Z", deadlineAt: "2099-01-01T06:00:00Z", verification: { status: "verified", source: "Synthetic source", verifiedAt: "2020-01-01T00:00:00Z" } };
  mockCampus = { data: { events: [verified, { _id: "demo", title: "Synthetic demo event", date: "2099-01-02" }] }, loading: false, refresh: jest.fn() };
  mount(<Events />);
  expect(screen.getByText("Synthetic demo event")).toBeTruthy();
  expect(screen.getByText("Unverified / demo record")).toBeTruthy();
  fireEvent.change(screen.getByLabelText("Calendar view"), { target: { value: "upcoming" } });
  expect(screen.queryByText("Synthetic demo event")).toBeNull();
  expect(screen.getByText("Synthetic verified event")).toBeTruthy();
  fireEvent.change(screen.getByLabelText("Calendar view"), { target: { value: "deadlines" } });
  expect(screen.getByText(/Deadline:/)).toBeTruthy();
});
test("notification loading, guest read/unread and unread filter work without push permission", async () => {
  mount(<NotificationCenter />);
  expect(screen.getByRole("status").textContent).toMatch(/Loading/);
  await screen.findByText(note.title);
  fireEvent.click(screen.getByRole("button", { name: `Mark ${note.title} read` }));
  fireEvent.change(screen.getByLabelText("Filter notifications"), { target: { value: "unread" } });
  expect(screen.queryByText(note.title)).toBeNull();
  expect(screen.getByText("No unread updates on this page")).toBeTruthy();
  expect(api.readNotification).not.toHaveBeenCalled();
  expect(JSON.parse(localStorage.getItem("aikya_notification_reads"))[note._id]).toBeTruthy();
  expect(screen.getByRole("button", { name: /Enable public push/ }).disabled).toBe(true);
});
test("server read state is account scoped and errors are retryable", async () => {
  mockUser = { role: "faculty", id: "synthetic" };
  api.notifications.mockRejectedValueOnce(new Error("synthetic private diagnostic"));
  mount(<NotificationCenter />);
  await screen.findByRole("alert");
  expect(screen.queryByText("synthetic private diagnostic")).toBeNull();
  fireEvent.click(screen.getByRole("button", { name: "Retry notifications" }));
  await screen.findByText(note.title);
  fireEvent.click(screen.getByRole("button", { name: `Mark ${note.title} read` }));
  await screen.findByRole("button", { name: `Mark ${note.title} unread` });
  expect(api.readNotification).toHaveBeenCalledWith(note._id, true);
});
test("pagination, expired records and empty states are explicit", async () => {
  api.notifications.mockResolvedValueOnce({ items: [{ ...note, expiresAt: "2020-01-02T00:00:00Z" }], hasMore: true }).mockResolvedValue({ items: [], hasMore: false });
  mount(<NotificationCenter />);
  await screen.findByText("No current announcements");
  fireEvent.click(screen.getByRole("button", { name: "More updates" }));
  await screen.findByText("Page 2");
  expect(api.notifications.mock.calls[1][0]).toBe(2);
});
test("campus timestamps and wall-time controls do not depend on device timezone", () => {
  const utc = "2030-01-01T18:30:00.000Z";
  expect(campusISO("2030-01-02T00:00")).toBe(utc);
  expect(campusInput(utc)).toBe("2030-01-02T00:00");
  expect(campusTimestamp(utc)).toMatch(/2 Jan 2030/);
  expect(campusTimestamp("bad")).toBe("Time unavailable");
  const event = { startsAt: "2099-01-01T00:00:00Z", verification: { status: "verified", source: "Synthetic", verifiedAt: "2020-01-01T00:00:00Z" } };
  expect(upcomingEvents([event, { ...event, verification: { status: "unverified" } }])).toHaveLength(1);
});
test("admin can edit a draft, schedule with verified source and cancel without deleting history", async () => {
  api.adminNotifications.mockResolvedValue({ items: [{ ...note, status: "draft", audience: "public", verification: { status: "unverified" } }], hasMore: false });
  api.saveNotification.mockResolvedValue({}); api.cancelNotification.mockResolvedValue({});
  mount(<NotificationAdmin />);
  fireEvent.click(await screen.findByRole("button", { name: `Edit ${note.title}` }));
  fireEvent.change(screen.getByLabelText("Official source/reference"), { target: { value: "Synthetic official circular" } });
  fireEvent.click(screen.getByRole("checkbox"));
  fireEvent.change(screen.getByLabelText("Save as"), { target: { value: "scheduled" } });
  fireEvent.click(screen.getByRole("button", { name: "Save announcement" }));
  await screen.findByText(/Announcement saved/);
  expect(api.saveNotification.mock.calls[0][0]).toBe(note._id);
  expect(api.saveNotification.mock.calls[0][1].verification.status).toBe("verified");
  expect(api.saveNotification.mock.calls[0][1].timezone).toBe("Asia/Kolkata");
  fireEvent.click(screen.getByRole("button", { name: `Cancel ${note.title}` }));
  await screen.findByText(/Announcement cancelled/);
  expect(api.cancelNotification).toHaveBeenCalledWith(note._id);
});
